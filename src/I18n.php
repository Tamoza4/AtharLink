    private static ?string $currentLang = null;

    /**
     * Get active language code ('ar' or 'en')
     */
    public static function getLang(): string
    {
        if (self::$currentLang === null) {
            $lang = $_COOKIE['athar_lang'] ?? 'en';
            self::$currentLang = ($lang === 'ar') ? 'ar' : 'en';
        }
        return self::$currentLang;
    }

    /**
     * Set active language code explicitly
     */
    public static function setLang(string $lang): void
    {
        self::$currentLang = ($lang === 'en') ? 'en' : 'ar';
    }

    /**
     * Get HTML direction attribute
     */
    public static function getDir(): string
    {
        return self::getLang() === 'ar' ? 'rtl' : 'ltr';
    }

    /**
     * Translate key with optional parameter replacements
     */
    public static function t(string $key, array $replace = []): string
    {
        $lang = self::getLang();
        $translations = self::getDictionary($lang);

        $text = $translations[$key] ?? $key;

        foreach ($replace as $placeholder => $value) {
            $text = str_replace(':' . $placeholder, (string)$value, $text);
        }

        return $text;
    }

